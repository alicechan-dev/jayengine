glm::vec3 cubePosition = glm::vec3(0.0f,  0.0f,  0.0f);     // scene stuff

size_t width = 800;
size_t height = 600;




// main
int main()
{
    Window window(width, height);    
    
    Camera camera(glm::vec3(.0f, .0f, 3.f), width, height);

    // create a shader
    Shader ourShader("./shaders/shader.vs", "./shaders/shader.fs");

    // textures preparage
    Texture texture1("./resources/container.jpg", false);
    Texture texture2("./resources/awesomeface.png", true);

    Geometry mesh(vertices);

    ourShader.use();
    ourShader.setInt("texture1", 0);    // scene stuff
    ourShader.setInt("texture2", 1);    // scene stuff

    window.maintainWindow([&]() {
        // firstly we need to arrange the rendering program for specific mesh 
        // going to be written below     
        texture1.use(GL_TEXTURE0);      // scene stuff
        texture2.use(GL_TEXTURE1);      // scene stuff

        // using camera's to precalculate projection and view to prepare datas for camera
        camera.use();

        Transform transform(cubePosition, glm::vec3(0,0,0));        // scene stuff

        mesh.use(ourShader, camera.getView(), camera.getProj(), transform);
    });

    return 0;
}
